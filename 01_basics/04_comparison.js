// Assignment operators

console.log( 2 > 1)
console.log( 2 >= 1)
console.log( 2 < 1)
console.log( 2 <= 1)
console.log( 2 == 1)
console.log( 2 != 1)

console.log("2" > 1);

// This type of converstions should be avoided completely
console.log(null == 0)
console.log(null >= 0)
console.log(null <= 0)

console.log(undefined == 0)
console.log(undefined >= 0)
console.log(undefined <= 0)

// === "Strict check"
// Checks both value and datatype

console.log("2" === 2)
console.log("2" === "2")